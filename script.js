function newGame(){
  const pool = DICT[state.len].keys;
  const key = pool[Math.floor(Math.random()*pool.length)];
  state.answer = key;
  state.answerRaw = DICT[state.len].words.get(key);
  state.rows = [];
  state.cur = Array(state.len).fill('');
  state.cursor = 0;
  state.row = 0;
  state.status = 'playing';
  state.letterState = {};
  state.ghosts = {};
  state.hintLevel = 0;
  state.carried = new Set();
  endEl.innerHTML = '';
  hintEl.innerHTML = '';
  drawBoard();
  drawKeyboard();
  markActiveRow();
  renderCurrent();
}

function drawBoard(){
  board.innerHTML='';
  board.style.setProperty('--tile', `clamp(30px, ${Math.min(72/state.len, 14)}vw, ${state.len>6?52:62}px)`);
  for(let r=0;r<state.tries;r++){
    const row=document.createElement('div');
    row.className='row'; row.dataset.row=r;
    row.style.gridTemplateColumns=`repeat(${state.len}, var(--tile))`;
    for(let c=0;c<state.len;c++){
      const t=document.createElement('div');
      t.className='tile'; t.dataset.col=c;
      row.appendChild(t);
    }
    board.appendChild(row);
  }
}

