function press(k){
  if(state.status!=='playing') {
    if(k==='↵') newGame();
    return;
  }
  if(k==='↵') return submit();
  if(k==='⌫'){
    if(state.cur[state.cursor]){
      state.cur[state.cursor] = '';
      state.carried.delete(state.cursor);
      sfx.del();
    } else if(state.cursor > 0){
      state.cursor--;
      state.cur[state.cursor] = '';
      state.carried.delete(state.cursor);
      sfx.del();
    }
    return renderCurrent();
  }
  if(/^[a-z]$/.test(k)){
    state.cur[state.cursor] = k;
    state.carried.delete(state.cursor);
    sfx.key();
    if(state.cursor < state.len-1) state.cursor++;
    renderCurrent();
  }
}
document.addEventListener('keydown', e=>{
  if(e.metaKey||e.ctrlKey||e.altKey) return;
  if(document.querySelector('.sheet.open')){ if(e.key==='Escape') closeSheets(); return; }
  if(e.key==='Enter') press('↵');
  else if(e.key==='Backspace') press('⌫');
  else {
    const k = norm(e.key);
    if(/^[a-z]$/.test(k) && e.key.length<=2) press(k);
  }
});

function renderCurrent(){
  const row = board.children[state.row];
  if(!row) return;
  [...row.children].forEach((tile,i)=>{
    const ch = state.cur[i];
    const ghost = state.ghosts[i];
    tile.textContent = ch || (ghost ? ghost : '');
    tile.classList.toggle('filled', !!ch);
    tile.classList.toggle('ghost', !ch && !!ghost);
    tile.classList.toggle('carried', !!ch && state.carried.has(i));
    tile.classList.toggle('active', i===state.cursor);
  });
}

/* =========================================================
   AVALIAÇÃO
   ========================================================= */
function evaluate(guess, answer){
  const res = Array(guess.length).fill('absent');
  const rest = {};
  for(let i=0;i<answer.length;i++){
    if(guess[i]===answer[i]) res[i]='correct';
    else rest[answer[i]]=(rest[answer[i]]||0)+1;
  }
  for(let i=0;i<guess.length;i++){
    if(res[i]==='correct') continue;
    const c=guess[i];
    if(rest[c]>0){ res[i]='present'; rest[c]--; }
  }
  return res;
}

function hardModeError(guess){
  // toda letra verde precisa estar na mesma posição; toda azul precisa reaparecer
  for(const past of state.rows){
    for(let i=0;i<state.len;i++){
      if(past.res[i]==='correct' && guess[i]!==past.guess[i])
        return `A ${i+1}ª letra precisa ser ${past.guess[i].toUpperCase()}`;
    }
    for(let i=0;i<state.len;i++){
      if(past.res[i]==='present' && !guess.includes(past.guess[i]))
        return `O palpite precisa conter ${past.guess[i].toUpperCase()}`;
    }
  }
  return null;
}

function submit(){
  if(state.cur.includes('')) return reject('Faltam letras');
  const g = state.cur.join('');
  const dict = DICT[state.len];
  if(!state.free && !dict.words.has(g)) return reject('Palavra não está na lista');
  if(state.hard){
    const err = hardModeError(g);
    if(err) return reject(err);
  }

  const res = evaluate(g, state.answer);
  state.rows.push({guess:g, res});
  const row = board.children[state.row];
  row.classList.remove('active-row');
  [...row.children].forEach(t=>t.classList.remove('active'));

  [...row.children].forEach((tile,i)=>{
    setTimeout(()=>{
      tile.classList.add('reveal');
      setTimeout(()=>{
        tile.classList.add(res[i]);
        // mostra o acento da resposta quando a letra está certa no lugar
        tile.textContent = res[i]==='correct' ? state.answerRaw[i] : g[i];
        sfx[res[i]]();
      },250);
    }, i*180);
    // prioridade: verde > azul > cinza
    const prev = state.letterState[g[i]];
    const rank = {absent:1, present:2, correct:3};
    if(!prev || rank[res[i]] > rank[prev]) state.letterState[g[i]] = res[i];
  });

  const delay = state.len*180 + 320;
  setTimeout(paintKeyboard, delay);

  // leva pra próxima linha as letras amarelas (presentes, posição errada) já
  // digitadas, pra o jogador não precisar redigitar o que já descobriu
  const nextCur = Array(state.len).fill('');
  const nextCarried = new Set();
  for(let i=0;i<state.len;i++){
    if(res[i]==='present'){ nextCur[i] = g[i]; nextCarried.add(i); }
  }
  state.cur = nextCur;
  state.carried = nextCarried;
  const firstEmpty = state.cur.findIndex(c=>!c);
  state.cursor = firstEmpty === -1 ? 0 : firstEmpty;
  state.row++;

  if(g === state.answer){
    state.status='win';
    setTimeout(()=>{ row.classList.add('win'); finish(true); }, delay);
  } else if(state.row >= state.tries){
    state.status='lose';
    setTimeout(()=>finish(false), delay);
  } else {
    setTimeout(maybeHint, delay + 150);
  }
  markActiveRow();
  renderCurrent();
}

function reject(msg){
  sfx.error();
  say(msg);
  const row=board.children[state.row];
  if(row){ row.classList.add('shake'); setTimeout(()=>row.classList.remove('shake'),500); }
}

function say(msg){
  const el=document.createElement('div');
  el.className='msg'; el.textContent=msg;
  toast.appendChild(el);
  setTimeout(()=>el.remove(), 1600);
}

