function press(k){
  // 'ending': acerto/erro final já detectado, mas a animação de revelação
  // ainda não terminou — ignora tudo (inclusive Enter) até finish() rodar,
  // senão um Enter repetido nesse meio-tempo reinicia o jogo antes da hora
  // e corrompe a tela de fim (setTimeout antigo mexendo no jogo novo)
  if(state.status==='ending') return;
  if(state.status!=='playing') {
    if(k==='↵') newGame();
    return;
  }
  if(k==='↵') return submit();
  if(k==='⌫'){
    // nunca apaga uma casinha travada (verde-limão, posição confirmada), mesmo
    // que o cursor tenha pousado nela (ex.: era a última casinha da linha)
    if(state.cur[state.cursor] && !state.locked.has(state.cursor)){
      state.cur[state.cursor] = '';
      sfx.del();
    } else {
      // pula pra trás as casinhas já travadas até achar uma editável
      let i = state.cursor - 1;
      while(i > 0 && state.locked.has(i)) i--;
      if(i >= 0 && !state.locked.has(i)){
        state.cursor = i;
        state.cur[i] = '';
        sfx.del();
      }
    }
    return renderCurrent();
  }
  if(/^[a-z]$/.test(k)){
    if(state.locked.has(state.cursor)) return;
    state.cur[state.cursor] = k;
    sfx.key();
    // pula pra frente as casinhas já travadas (verde-limão, posição confirmada),
    // incluindo a última casinha da linha (por isso "< state.len", não "state.len-1")
    let i = state.cursor + 1;
    while(i < state.len && state.locked.has(i)) i++;
    if(i < state.len) state.cursor = i;
    renderCurrent();
  }
}
document.addEventListener('keydown', e=>{
  if(e.metaKey||e.ctrlKey||e.altKey) return;
  if(e.repeat) return; // ignora repetição automática ao segurar a tecla (Enter em especial)
  if(document.querySelector('.sheet.open')){ if(e.key==='Escape') closeSheets(); return; }
  if(e.key==='Enter') press('↵');
  else if(e.key==='Backspace') press('⌫');
  else {
    const k = norm(e.key);
    if(/^[a-z]$/.test(k) && e.key.length<=2) press(k);
  }
});

function renderCurrent(){
  const row = board.children[state.row];
  if(!row) return;
  [...row.children].forEach((tile,i)=>{
    const ch = state.cur[i];
    const ghost = state.ghosts[i];
    const locked = state.locked.has(i);
    // travada (verde-limão): mostra sempre a letra com acento/til da resposta.
    // state.cur guarda a letra sem acento (é o que é comparado com o dicionário),
    // então sem isso a casinha travada aparecia sem acento na linha atual.
    tile.textContent = ch ? (locked ? state.answerRaw[i] : ch) : (ghost ? ghost : '');
    tile.classList.toggle('filled', !!ch);
    tile.classList.toggle('ghost', !ch && !!ghost);
    tile.classList.toggle('locked', locked);
    tile.classList.toggle('active', i===state.cursor);
  });
}

/* =========================================================
   AVALIAÇÃO
   ========================================================= */
function evaluate(guess, answer){
  const res = Array(guess.length).fill('absent');
  const rest = {};
  for(let i=0;i<answer.length;i++){
    if(guess[i]===answer[i]) res[i]='correct';
    else rest[answer[i]]=(rest[answer[i]]||0)+1;
  }
  for(let i=0;i<guess.length;i++){
    if(res[i]==='correct') continue;
    const c=guess[i];
    if(rest[c]>0){ res[i]='present'; rest[c]--; }
  }
  return res;
}

function hardModeError(guess){
  // toda letra verde precisa estar na mesma posição; toda azul precisa reaparecer
  for(const past of state.rows){
    for(let i=0;i<state.len;i++){
      if(past.res[i]==='correct' && guess[i]!==past.guess[i])
        return `A ${i+1}ª letra precisa ser ${past.guess[i].toUpperCase()}`;
    }
    for(let i=0;i<state.len;i++){
      if(past.res[i]==='present' && !guess.includes(past.guess[i]))
        return `O palpite precisa conter ${past.guess[i].toUpperCase()}`;
    }
  }
  return null;
}

function submit(){
  if(state.cur.includes('')) return reject('Faltam letras');
  const g = state.cur.join('');
  const dict = DICT[state.len];
  if(!state.free && !dict.words.has(g)) return reject('Palavra não está na lista');
  if(state.hard){
    const err = hardModeError(g);
    if(err) return reject(err);
  }

  const res = evaluate(g, state.answer);
  state.rows.push({guess:g, res});
  const row = board.children[state.row];
  row.classList.remove('active-row');
  [...row.children].forEach(t=>t.classList.remove('active'));

  // trava pra todo callback adiado abaixo: se uma partida nova começar
  // (newGame() incrementa gameId) antes do setTimeout disparar, o callback
  // vira no-op em vez de mexer no estado do jogo seguinte
  const gameId = state.gameId;

  [...row.children].forEach((tile,i)=>{
    setTimeout(()=>{
      if(state.gameId!==gameId) return;
      tile.classList.add('reveal');
      setTimeout(()=>{
        if(state.gameId!==gameId) return;
        tile.classList.add(res[i]);
        // mostra o acento da resposta quando a letra está certa no lugar
        tile.textContent = res[i]==='correct' ? state.answerRaw[i] : g[i];
        sfx[res[i]]();
      },250);
    }, i*180);
    // prioridade: verde > azul > cinza
    const prev = state.letterState[g[i]];
    const rank = {absent:1, present:2, correct:3};
    if(!prev || rank[res[i]] > rank[prev]) state.letterState[g[i]] = res[i];
  });

  const delay = state.len*180 + 320;
  setTimeout(()=>{ if(state.gameId===gameId) paintKeyboard(); }, delay);

  state.row++;

  if(g === state.answer){
    // estado transitório: já sabemos que ganhou, mas só vira 'win' de fato
    // (e Enter volta a reiniciar o jogo) quando a animação terminar — ver
    // guard de state.status==='ending' em press()
    state.status='ending';
    setTimeout(()=>{
      if(state.gameId!==gameId) return;
      row.classList.add('win');
      state.status='win';
      finish(true);
    }, delay);
  } else if(state.row >= state.tries){
    state.status='ending';
    setTimeout(()=>{
      if(state.gameId!==gameId) return;
      state.status='lose';
      finish(false);
    }, delay);
  } else {
    // leva pra próxima linha as letras verde-limão (posição confirmada) já
    // descobertas em qualquer tentativa anterior, travadas nas posições certas
    const nextCur = Array(state.len).fill('');
    const nextLocked = new Set();
    state.rows.forEach(r=>{
      r.res.forEach((v,i)=>{ if(v==='correct'){ nextCur[i] = r.guess[i]; nextLocked.add(i); } });
    });
    state.cur = nextCur;
    state.locked = nextLocked;
    const firstEmpty = state.cur.findIndex(c=>!c);
    state.cursor = firstEmpty === -1 ? 0 : firstEmpty;
    renderCurrent();
    setTimeout(()=>{ if(state.gameId===gameId) maybeHint(); }, delay + 150);
  }
  markActiveRow();
}

function reject(msg){
  sfx.error();
  say(msg);
  const row=board.children[state.row];
  if(row){ row.classList.add('shake'); setTimeout(()=>row.classList.remove('shake'),500); }
}

function say(msg){
  const el=document.createElement('div');
  el.className='msg'; el.textContent=msg;
  toast.appendChild(el);
  setTimeout(()=>el.remove(), 1600);
}

/* =========================================================
   FIM DE JOGO
   ========================================================= */
const ELOGIOS=['Impressionante!','Excelente!','Muito bem!','Boa!','Ufa!','Essa foi por pouco!'];
function finish(won){
  hintEl.innerHTML='';
  state.hintKey=null;
  setGroupHintBtn(false);
  paintKeyboard();
  won ? sfx.win() : sfx.lose();
  stats.played++;
  if(won){
    stats.wins++; stats.streak++;
    if(state.row>=1 && state.row<=stats.dist.length) stats.dist[state.row-1]++;
  } else { stats.streak=0; }
  store.set('dito:stats', stats);
  renderStats();

  if(state.mode==='daily'){
    // só uma partida diária por dia: guarda o resultado pra bloquear replay
    store.set('dito:daily', {
      date:todayStr(), len:state.len, tries:state.tries,
      rows:state.rows, status:state.status, answerRaw:state.answerRaw
    });
  }

  // terminada a partida do desafio, libera as configurações de novo
  if(state.duel) endDuel();

  renderEndbar(
    won ? ELOGIOS[Math.max(0, Math.min(state.row-1, ELOGIOS.length-1))] : 'A palavra era',
    won ? `Acertou em ${state.row} de ${state.tries}` : 'Fica para a próxima',
    { again: state.mode!=='daily' }
  );
}

