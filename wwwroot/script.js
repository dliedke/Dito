    document.getElementById('tabDaily').setAttribute('aria-pressed', false);
    document.getElementById('tabFree').setAttribute('aria-pressed', true);
    buildThemeSelect();
    buildSegments();
    newGame(incoming.key);
    say('Desafio recebido! Adivinhe a palavra do seu amigo.');
